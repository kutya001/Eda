A = dt.date(2026, 10, 22)  # опорная дата демо-данных (четверг)
random.seed(7)


def d(n):
    return (A + dt.timedelta(days=n)).isoformat()


def st(n, hm):
    return f'{d(n)} {hm}'


def wd(n):
    return (A + dt.timedelta(days=n)).isoweekday()


def items(prefix, rows, note_key=None):
    out = []
    for i, r in enumerate(rows):
        name, note = (r, '') if isinstance(r, str) else r
        out.append({'code': f'{prefix}-{i + 1:03d}', 'name': name, 'note': note, 'active': True, 'order': i + 1})
    return out


