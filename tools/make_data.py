def expand(line, menu):
    """Строка заказа → блюда и порции (комплекс раскрывается по меню дня)."""
    if line['kind'] == 'd':
        return {line['id']: line['qty']}
    it = next(i for i in menu if i['kind'] == 'c' and i['id'] == line['id'])
    out = {}
    for sl, dd in it['fill'].items():
        if dd:
            out[dd] = out.get(dd, 0) + line['qty']
    return out


